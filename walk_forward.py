"""Timestamp-safe selected-timeframe walk-forward simulator.

All timestamps are candle OPEN times in Unix milliseconds. A candle is usable only
when open_time + timeframe_duration <= decision_time. Entry occurs at the next open of the fastest selected timeframe. No synthetic historical exchange data is generated by this module.
"""
from __future__ import annotations

from typing import Any, Dict, List, Tuple
from math import isfinite
from signal_engine import SUPPORTED_TFS, REQUIRED_TFS, analyze_market

DURATION_MS = {"1m": 60_000, "3m": 180_000, "5m": 300_000, "15m": 900_000, "30m": 1_800_000, "1h": 3_600_000, "4h": 14_400_000}
MAX_ENTRY_GAP_ATR = 0.25


def _timestamp(row: Dict[str, Any]) -> int:
    for key in ("timestamp", "open_time", "time"):
        if row.get(key) is not None:
            value = int(row[key])
            if value < 0:
                raise ValueError("timestamps must be non-negative Unix milliseconds")
            return value
    raise ValueError("every candle must contain timestamp/open_time/time in Unix milliseconds")


def _validate(timeframes: Dict[str, list], selected_tfs=None) -> Dict[str, List[Tuple[int, dict]]]:
    selected_tfs = tuple(REQUIRED_TFS if selected_tfs is None else selected_tfs)
    missing = [tf for tf in selected_tfs if tf not in timeframes]
    if missing:
        raise ValueError("Missing selected timeframes: " + ", ".join(missing))
    indexed = {}
    for tf in selected_tfs:
        rows = timeframes[tf]
        pairs = [(_timestamp(row), row) for row in rows]
        stamps = [x[0] for x in pairs]
        if any(b <= a for a, b in zip(stamps, stamps[1:])):
            raise ValueError(f"{tf} timestamps must be strictly increasing")
        gap = next(((a, b) for a, b in zip(stamps, stamps[1:])
                    if b - a != DURATION_MS[tf]), None)
        if gap is not None:
            raise ValueError(
                f"{tf} candles must be contiguous {tf} bars; first gap is {gap[0]} -> {gap[1]} "
                f"(delta {gap[1]-gap[0]} ms); gaps are not silently filled"
            )
        indexed[tf] = pairs
    return indexed


def _closed_history(pairs, tf: str, decision_ms: int) -> List[dict]:
    duration = DURATION_MS[tf]
    # Candle open time + duration is its close time; equality is closed and usable.
    return [row for opened, row in pairs if opened + duration <= decision_ms]


def run_walk_forward(timeframes: Dict[str, list], *, fee_bps_per_side: float = None,
                     fee_bps_open: float = None, fee_bps_close: float = None,
                     slippage_bps_per_side: float, initial_equity: float = 10_000.0,
                     risk_fraction: float = 0.005, max_holding_bars: int = 72,
                     allocation: Tuple[float, float, float] = (1/3, 1/3, 1/3),
                     selected_timeframes=None) -> Dict[str, Any]:
    """Long-only reversal backtest: enter on LONG and exit only on SHORT.

    No SHORT position is ever opened. A LONG remains open through WAIT and
    repeated LONG signals. The SHORT decision is confirmed on a closed candle
    and the exit is modeled at the next open of the fastest selected timeframe. ATR is used only as a sizing
    risk reference; it is not an active stop and no take-profit exits are used.
    """
    if fee_bps_per_side is not None:
        fee_bps_open = fee_bps_open if fee_bps_open is not None else fee_bps_per_side
        fee_bps_close = fee_bps_close if fee_bps_close is not None else fee_bps_per_side
    if fee_bps_open is None or fee_bps_close is None:
        raise ValueError("explicit opening and closing exchange fee rates are required")
    if min(fee_bps_open, fee_bps_close, slippage_bps_per_side) < 0:
        raise ValueError("exchange fee and slippage assumptions cannot be negative")
    if initial_equity <= 0 or not 0 < risk_fraction <= 0.05 or max_holding_bars < 1:
        raise ValueError("invalid equity, risk fraction, or holding horizon")
    selected_tfs = tuple(REQUIRED_TFS if selected_timeframes is None else dict.fromkeys(selected_timeframes))
    if not selected_tfs or any(tf not in SUPPORTED_TFS for tf in selected_tfs):
        raise ValueError("selected_timeframes must contain one or more supported intervals")
    indexed = _validate(timeframes, selected_tfs)
    base_tf = min(selected_tfs, key=lambda tf: DURATION_MS[tf])
    base = indexed[base_tf]
    if len(base) < 61:
        raise ValueError(f"at least 61 timestamped {base_tf} candles are required")

    equity = float(initial_equity)
    peak = equity
    max_dd = 0.0
    trades: List[dict] = []
    position = None
    entry_gap_skips = 0
    invalid_level_skips = 0
    decision_diagnostics = {"evaluated": 0, "no_signal": 0, "long_candidates": 0,
                            "short_candidates": 0, "invalid_market_data": 0,
                            "rejection_reason_counts": {}, "rejected_decision_samples": []}

    def apply_funding(pos, end_index):
        cash = 0.0
        bps_total = 0.0
        events = 0
        for j in range(pos["entry_index"], end_index + 1):
            row = base[j][1]
            settle_time, rate = row.get("funding_settle_time"), row.get("funding_rate")
            if settle_time is None or rate is None:
                continue
            candle_open = base[j][0]
            if not candle_open < int(settle_time) <= candle_open + DURATION_MS[base_tf]:
                continue
            rate = float(rate)
            cash += pos["entry"] * pos["quantity"] * rate
            bps_total += rate * 10000
            events += 1
        return (cash if events else None, bps_total if events else None, events)

    def finish_position(pos, exit_index, raw_exit, reason):
        nonlocal equity, peak, max_dd
        exit_fill = raw_exit * (1 - slippage_bps_per_side / 10000)
        exit_slippage = abs(exit_fill - raw_exit) * pos["quantity"]
        close_fee = abs(exit_fill * pos["quantity"]) * fee_bps_close / 10000
        realized = (exit_fill - pos["entry_fill"]) * pos["quantity"]
        funding_cash, funding_bps, funding_events = apply_funding(pos, exit_index)
        fees = pos["entry_fee"] + close_fee
        net_pnl = realized - fees - (funding_cash or 0.0)
        start_equity = equity
        equity += net_pnl
        peak = max(peak, equity)
        max_dd = max(max_dd, (peak - equity) / peak if peak > 0 else 0.0)
        trades.append({
            "side": "LONG",
            "signal_time": pos["signal_time"],
            "entry_time": base[pos["entry_index"]][0],
            "exit_time": base[exit_index][0],
            "entry": pos["entry"],
            "exit": exit_fill,
            "exit_reason": reason,
            "closed_by_short_signal": reason == "opposite_short_signal",
            "position_quantity": pos["quantity"],
            "initial_notional": pos["entry"] * pos["quantity"],
            "risk_cash": pos["risk_cash"],
            "risk_fraction": risk_fraction,
            "risk_reference_distance": pos["risk_distance"],
            "risk_reference_price": pos["risk_reference_price"],
            "stop_loss": None,
            "take_profits": [],
            "fees_cash": fees,
            "slippage_cash": pos["entry_slippage"] + exit_slippage,
            "funding_bps": funding_bps,
            "funding_cash": funding_cash,
            "funding_mode": "historical_settlement_events" if funding_events else "not_supplied",
            "net_pnl": net_pnl,
            "net_return_pct": net_pnl / start_equity * 100 if start_equity else 0.0,
            "equity_after": equity,
        })

    i = 59
    while i + 1 < len(base):
        decision_open, decision_candle = base[i]
        decision_time = decision_open + DURATION_MS[base_tf]
        histories = {tf: _closed_history(indexed[tf], tf, decision_time) for tf in selected_tfs}
        if not histories[base_tf] or _timestamp(histories[base_tf][-1]) != decision_open:
            i += 1
            continue
        if min(len(histories[tf]) for tf in selected_tfs) < 60:
            i += 1
            continue

        signal = analyze_market({tf: histories[tf][-260:] for tf in selected_tfs}, selected_timeframes=selected_tfs)
        decision_diagnostics["evaluated"] += 1
        side = signal.get("signal")
        if side not in ("LONG", "SHORT"):
            decision_diagnostics["no_signal"] += 1
            if any(not report.get("valid", False) for report in signal.get("timeframes", {}).values()):
                decision_diagnostics["invalid_market_data"] += 1
            reasons = signal.get("rejection_reasons") or [signal.get("reason") or "unspecified_no_signal"]
            for reason in reasons:
                key = str(reason)
                counts = decision_diagnostics["rejection_reason_counts"]
                counts[key] = counts.get(key, 0) + 1
            if len(decision_diagnostics["rejected_decision_samples"]) < 500:
                decision_diagnostics["rejected_decision_samples"].append({
                    "decision_time": decision_time,
                    "reasons": [str(reason) for reason in reasons],
                    "reason": signal.get("reason"),
                    "timeframes": {
                        tf: {
                            "valid": report.get("valid"),
                            "bias": report.get("bias"),
                            "market_regime": report.get("market_regime"),
                            "high_volatility": report.get("high_volatility"),
                            "indicator_votes": report.get("indicator_votes"),
                        }
                        for tf, report in signal.get("timeframes", {}).items()
                    },
                })
            i += 1
            continue

        if side == "SHORT":
            decision_diagnostics["short_candidates"] += 1
            if position is not None:
                exit_index = i + 1
                raw_exit = float(base[exit_index][1]["open"])
                finish_position(position, exit_index, raw_exit, "opposite_short_signal")
                position = None
                i = exit_index
                continue
            # SHORT while flat is an exit instruction with nothing to close.
            i += 1
            continue

        decision_diagnostics["long_candidates"] += 1
        if position is not None:
            # Hold the existing LONG; same-side signals never pyramid or reset entry.
            i += 1
            continue

        entry_index = i + 1
        entry = float(base[entry_index][1]["open"])
        signal_close = float(decision_candle["close"])
        atr = (signal.get("timeframes", {}).get(base_tf, {})
               .get("indicators", {}).get("atr"))
        if (atr is None or not isfinite(float(atr)) or float(atr) <= 0
                or not isfinite(entry) or not isfinite(signal_close) or entry <= 0):
            invalid_level_skips += 1
            i += 1
            continue
        atr = float(atr)
        if abs(entry - signal_close) / atr > MAX_ENTRY_GAP_ATR:
            entry_gap_skips += 1
            i += 1
            continue

        risk_cash = equity * risk_fraction
        risk_distance = 1.5 * atr
        entry_fill = entry * (1 + slippage_bps_per_side / 10000)
        reference_exit = max(1e-12, entry - risk_distance)
        estimated_loss_per_unit = (
            risk_distance
            + entry * (fee_bps_open + slippage_bps_per_side) / 10000
            + reference_exit * (fee_bps_close + slippage_bps_per_side) / 10000
        )
        if estimated_loss_per_unit <= 0:
            invalid_level_skips += 1
            i += 1
            continue
        quantity = risk_cash / estimated_loss_per_unit
        entry_fee = abs(entry_fill * quantity) * fee_bps_open / 10000
        position = {
            "signal_time": decision_time,
            "entry_index": entry_index,
            "entry": entry,
            "entry_fill": entry_fill,
            "quantity": quantity,
            "entry_fee": entry_fee,
            "entry_slippage": abs(entry_fill - entry) * quantity,
            "risk_cash": risk_cash,
            "risk_distance": risk_distance,
            "risk_reference_price": reference_exit,
            "signal_snapshot": {
                "timeframes": {
                    tf: {
                        "bias": report.get("bias"),
                        "indicator_votes": report.get("indicator_votes"),
                        "high_volatility": report.get("high_volatility"),
                    }
                    for tf, report in signal.get("timeframes", {}).items()
                }
            },
        }
        i = entry_index

    # A position still open at the end of the historical sample is marked out at
    # the final candle close; it is not silently discarded from reported equity.
    if position is not None:
        last_index = len(base) - 1
        finish_position(position, last_index, float(base[last_index][1]["close"]), "end_of_data")

    returns = [t["net_return_pct"] for t in trades]
    wins = sum(t["net_pnl"] > 0 for t in trades)
    side_stats = {}
    for side in ("LONG", "SHORT"):
        rows = [t for t in trades if t["side"] == side]
        side_wins = sum(t["net_pnl"] > 0 for t in rows)
        side_stats[side] = {
            "trade_count": len(rows), "wins": side_wins,
            "losses": len(rows) - side_wins,
            "win_rate_pct": side_wins / len(rows) * 100 if rows else 0.0,
            "net_pnl": sum(t["net_pnl"] for t in rows),
        }
    max_consecutive_losses = current_losses = 0
    for trade in trades:
        if trade["net_pnl"] < 0:
            current_losses += 1
            max_consecutive_losses = max(max_consecutive_losses, current_losses)
        else:
            current_losses = 0
    gross_profit = sum(max(0.0, t["net_pnl"]) for t in trades)
    gross_loss = sum(min(0.0, t["net_pnl"]) for t in trades)
    return {
        "trades": trades,
        "trade_count": len(trades),
        "initial_equity": initial_equity,
        "final_equity": equity,
        "net_return_pct": (equity / initial_equity - 1) * 100,
        "win_rate_pct": wins / len(trades) * 100 if trades else 0.0,
        "profit_factor": gross_profit / abs(gross_loss) if gross_loss else (float("inf") if gross_profit else 0.0),
        "gross_profit": gross_profit,
        "gross_loss": gross_loss,
        "side_stats": side_stats,
        "max_consecutive_losses": max_consecutive_losses,
        "decision_diagnostics": decision_diagnostics,
        "entry_filter": {
            "max_entry_gap_atr": MAX_ENTRY_GAP_ATR,
            "entry_gap_skips": entry_gap_skips,
            "invalid_level_skips": invalid_level_skips,
            "levels_policy": "no active stop or take-profit; hold LONG until SHORT",
        },
        "max_drawdown_pct": max_dd * 100,
        "risk_fraction": risk_fraction,
        "fee_bps_open": fee_bps_open,
        "fee_bps_close": fee_bps_close,
        "slippage_bps_per_side": slippage_bps_per_side,
        "position_sizing": "risk_budget_uses_1.5_ATR_reference_only; no stop exit",
        "timestamp_alignment": "asof_closed_only",
        "selected_timeframes": list(selected_tfs),
        "execution_timeframe": base_tf,
        "funding_mode": "historical_settlement_events" if any(t["funding_mode"] == "historical_settlement_events" for t in trades) else "not_supplied",
        "note": "Long-only reversal model: LONG opens, SHORT closes at next execution-timeframe open, WAIT holds, and no SHORT position is opened. ATR is a sizing reference only, not an active stop. Positions still open at sample end are marked to the final close. Funding uses only supplied historical settlement events.",
    }
